const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'gas/Code.gs'), 'utf8');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const normalizer = app.slice(app.indexOf('function normalizeRankingData('), app.indexOf('function getAssetDataApi('));
const reference = fs.readFileSync(path.join(__dirname, 'fixtures/ranking-reference.js'), 'utf8');
let formatCalls = 0;
const input = [['date', 'person', 'category', 'memo', 'amount']];
const tables = { '入力データ': input, 'カテゴリマスタ': [['category', 'type'], ['食費', '月予算'], ['旅行', '年予算'], ['家賃', '固定費'], ['給与', '収入']] };
const ctx = vm.createContext({ Date, SpreadsheetApp: { openById: () => ({ getSheetByName: name => ({ getDataRange: () => ({ getValues: () => tables[name] }) }) }) }, Utilities: { formatDate: date => { formatCalls++; return `${date.getMonth()+1}/${date.getDate()}`; } } });
vm.runInContext(source + '\n' + reference + '\n' + normalizer, ctx);
const read = expression => JSON.parse(vm.runInContext(`JSON.stringify(${expression})`, ctx));
for (let i = 0; i < 6000; i++) input.push([new Date(2025 + i % 2, Math.floor(i/2) % 12, 1 + i % 27), ['共通', 'くる', 'ぐんま', '合計', '不明'][i % 5], ['食費', '旅行', '家賃', '給与'][i % 4], i % 7 === 0 ? '共通繰入' : 'memo', i % 19 === 0 ? 0 : i % 17 === 0 ? -100 : 100 + i % 50]);
const expected = read('getRankingDataReference()'); const originalCalls = formatCalls;
formatCalls = 0; const actual = read('getRankingData()'); const optimizedCalls = formatCalls;
assert.deepEqual(actual, expected);
const compact = read('getRankingData(true)');
assert.deepEqual(read('normalizeRankingData(getRankingData(true))'), expected);
assert.deepEqual(read('normalizeRankingData(getRankingData())'), expected, 'old API response remains compatible');
assert.ok(optimizedCalls < originalCalls, 'date formatting should be shared per identical timestamp');
assert.ok(Buffer.byteLength(JSON.stringify(compact)) < Buffer.byteLength(JSON.stringify(expected)), 'compact response should omit duplicate period lists');
const reduction = Math.round(100 * (1 - Buffer.byteLength(JSON.stringify(compact)) / Buffer.byteLength(JSON.stringify(expected))));
input.splice(1);
assert.deepEqual(read('normalizeRankingData(getRankingData(true))'), read('getRankingDataReference()'));
console.log(`PASS: ranking output unchanged for 6,000 rows and empty data; date formatting ${originalCalls} -> ${optimizedCalls}; response ${reduction}% smaller in fixture; legacy API supported.`);
